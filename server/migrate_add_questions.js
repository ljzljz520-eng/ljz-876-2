function migrate() {
  // 检查是否已经迁移过
  const existingCount = db.prepare('SELECT COUNT(*) as c FROM questions').get().c;
  if (existingCount >= 100) {
    console.log('题库已有', existingCount, '题，无需迁移。');
    return;
  }

  const insertQuestion = db.prepare(`
    INSERT INTO questions (chapter_id, type, content, options, answer, explanation, explanation_plain, version, is_active)
    VALUES (?, ?, ?, ?, ?, ?, ?, 1, 1)
  `);
  const insertVersion = db.prepare(`
    INSERT INTO question_versions (question_id, version, content, options, answer, explanation, explanation_plain, snapshot)
    VALUES (?, 1, ?, ?, ?, ?, ?, ?)
  `);

  const chapterIds = db.prepare('SELECT id FROM chapters ORDER BY sort_order').all().map(c => c.id);

  const insertMany = db.transaction((qs) => {
    for (const [chapterIdx, type, content, options, answer, explanation, explanation_plain] of qs) {
      const chapterId = chapterIds[chapterIdx];
      const result = insertQuestion.run(chapterId, type, content, options, answer, explanation, explanation_plain);
      const questionId = result.lastInsertRowid;
      const snapshot = JSON.stringify({
        id: questionId, chapter_id: chapterId, type, content,
        options: JSON.parse(options), answer, explanation, explanation_plain, version: 1,
      });
      insertVersion.run(questionId, content, options, answer, explanation, explanation_plain, snapshot);
    }
  });
  insertMany(additionalQuestions);

  const totalCount = db.prepare('SELECT COUNT(*) as c FROM questions WHERE is_active = 1').get().c;
  console.log(`迁移完成，新增 ${additionalQuestions.length} 题，题库现有 ${totalCount} 题。`);
}

migrate();
